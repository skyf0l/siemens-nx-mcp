"""Render docs/tools.md, the tool reference, from the catalogue and its generated schemas.

Per domain: every catalogue tool with its label, effect, description, arguments
(types and defaults from ``nx_mcp.sidecar.schema.input_schema``) and its NX 2406
acceptance evidence. ``--check`` reports drift without writing.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BUILD = "v2406"


def load_rows() -> list[dict]:
    """One row per catalogue tool (no NX, no bridge)."""
    src = str(ROOT / "src")
    if src not in sys.path:
        sys.path.insert(0, src)
    from nx_mcp.core import catalogue, evidence
    from nx_mcp.sidecar import schema

    found = evidence.load(ROOT / "src/nx_mcp/evidence")
    rows = []
    for name, spec in sorted(catalogue.load().items()):
        rows.append(
            {
                "name": name,
                "domain": spec.domain,
                "label": spec.label,
                "effect": spec.effect,
                "description": spec.description,
                "variants": list(spec.variant_values()),
                "schema": schema.input_schema(spec, call_keys=False),
                "evidence": found.get(name, {}).get(BUILD),
            }
        )
    return rows


def type_of(node: dict, defs: dict) -> str:
    """A short human-readable type for one JSON Schema node."""
    if "$ref" in node:
        return node["$ref"].rsplit("/", 1)[-1]
    if "const" in node:
        return f"`{node['const']}`"
    if "enum" in node:
        return " \\| ".join(f"`{value}`" for value in node["enum"])
    for key in ("anyOf", "oneOf"):
        if key in node:
            return " or ".join(type_of(sub, defs) for sub in node[key])
    kind = node.get("type")
    if isinstance(kind, list):
        return " or ".join(kind)
    if kind == "array":
        item = type_of(node.get("items", {}), defs)
        low, high = node.get("minItems"), node.get("maxItems")
        size = f"{low}" if low == high and low is not None else f"{low or 0}-{high}"
        return f"array[{size}] of {item}"
    if kind == "object" and "properties" in node:
        return "object {" + ", ".join(node["properties"]) + "}"
    return kind or "any"


def argument_rows(schema: dict) -> list[str]:
    defs = schema.get("$defs", {})
    required = set(schema.get("required", []))
    lines = []
    for name, prop in schema.get("properties", {}).items():
        default = "required" if name in required else "optional"
        if "default" in prop:
            default = "`" + json.dumps(prop["default"]) + "`"
        note = prop.get("description") or defs.get(prop.get("$ref", "").rsplit("/", 1)[-1], {}).get(
            "description", ""
        )
        lines.append(f"| `{name}` | {type_of(prop, defs)} | {default} | {cell(note)} |")
    return lines


def evidence_text(row: dict) -> str:
    entry = row.get("evidence")
    if not entry:
        return "untested (refused in production)"
    tested = sorted(entry.get("variants") or [])
    missing = sorted(set(row["variants"]) - set(tested))
    text = "tested"
    if row["variants"]:
        text += (
            " (all variants)"
            if not missing
            else f": {', '.join(tested)} (untested: {', '.join(missing)})"
        )
    if entry.get("scenario"):
        text += f"; {entry.get('checks', 0)} checks in `{entry['scenario']}`"
    return text


def cell(value: object) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ")


def render(rows: list[dict]) -> str:
    domains = sorted({row["domain"] for row in rows})
    tested = sum(1 for row in rows if row.get("evidence"))
    lines = [
        "# Tool reference",
        "",
        "Generated by `scripts/generate_tool_reference.py` from the catalogue "
        "(`nx_mcp.core.catalogue`), the generated input schemas and the acceptance evidence in "
        "`src/nx_mcp/evidence/`; do not edit by hand. Run the script to regenerate, or add "
        "`--check` to detect drift.",
        "",
        f"{len(rows)} catalogue tools in {len(domains)} domains; {tested} have NX 2406 acceptance "
        "evidence. The agent profile discovers them with `nx_find_tools`/`nx_get_tool_schemas` "
        "and calls them through `nx_invoke`/`nx_invoke_read`; mutating tools also take "
        "`operation_id` and `intent`. Per-build scope: [capability matrix](capability-matrix.md).",
        "",
    ]
    lines += [f"- [{domain}](#{domain.replace('_', '-')})" for domain in domains]
    for domain in domains:
        lines += ["", f"## {domain}"]
        for row in (r for r in rows if r["domain"] == domain):
            lines += [
                "",
                f"### `{row['name']}`",
                "",
                f"**{cell(row['label'])}** · effect `{row['effect']}` · NX 2406: {evidence_text(row)}",
                "",
                row["description"],
                "",
            ]
            args = argument_rows(row["schema"])
            if args:
                lines += [
                    "| Argument | Type | Default | Notes |",
                    "| --- | --- | --- | --- |",
                    *args,
                ]
            else:
                lines.append("No arguments.")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ROOT / "docs/tools.md")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = render(load_rows())
    if args.check:
        if not args.output.exists() or args.output.read_text(encoding="utf-8") != result:
            print(f"Tool reference is stale: {args.output}; regenerate with this script.")
            return 1
        print("Tool reference matches the catalogue.")
        return 0
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(result, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
