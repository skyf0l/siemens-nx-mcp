"""Render the token budget table of docs/design/architecture.md (section 6).

The caps are the constants of ``tests/sidecar/test_budget.py`` and the measured values its
``measure()`` (the same measurement the budget tests assert), so the table is never edited
by hand. The table sits between the BEGIN/END markers below; ``--check`` reports drift
without writing. Needs the package's dependencies (pydantic, mcp) and pytest.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / "docs/design/architecture.md"
BEGIN = "<!-- BEGIN budget table: generated by scripts/generate_budget_table.py -->"
END = "<!-- END budget table -->"


def load() -> tuple[object, dict]:
    """``(test_budget module, measured values)`` (no NX, no bridge)."""
    for path in (str(ROOT), str(ROOT / "src")):
        if path not in sys.path:
            sys.path.insert(0, path)
    from tests.sidecar import test_budget

    return test_budget, test_budget.measured_now()


def n(value: float) -> str:
    """``15,070``; a fractional value keeps one decimal (``952.0``)."""
    return f"{value:,.0f}" if float(value).is_integer() else f"{value:,.1f}"


def tokens(chars: float, per_token: float) -> str:
    return f"about {chars / per_token / 1000:.1f}K tokens"


def render(b, m: dict) -> str:
    """The table: ``b`` holds the caps (test_budget), ``m`` the measured values."""
    t = b.CHARS_PER_TOKEN
    plain, union = m["plain"], m["union"]
    rows = [
        (
            "`agent` profile listing (4 gateways + 14 core tools; paid every turn)",
            f"{n(b.AGENT_LISTING_BASE)} + {b.PER_DOMAIN} per domain = {n(b.AGENT_LISTING)} "
            f"({m['domains']} domains)",
            f"{n(m['agent_listing'])} ({tokens(m['agent_listing'], t)})",
        ),
        (
            "`agent` server instructions (once per session)",
            n(b.INSTRUCTIONS_CAP),
            n(m["instructions"]),
        ),
        (
            "Full listing (name + description + input schema, call keys included)",
            f"mean {n(b.FULL_MEAN_PER_TOOL)} per listed tool",
            f"mean {n(round(m['full_mean'], 1))} over {m['full_tools']} tools "
            f"({n(m['full_total'])}, {tokens(m['full_total'], t)})",
        ),
        (
            "Tool definition (name + description + input schema, no call keys)",
            f"each {n(b.DEFINITION_CAP)}; {n(b.UNION_CAP)} for unions",
            f"max {n(plain[2])} ({plain[0]} plain tools), {n(union[2])} ({union[0]} unions)",
        ),
        (
            "Tool definition drift (75th percentile per kind)",
            f"plain {n(b.PLAIN_P75)}, union {n(b.UNION_P75)}",
            f"plain {n(plain[1])}, union {n(union[1])}",
        ),
        (
            f"`nx_find_tools` page ({m['find_queries']} realistic queries)",
            f"row {b.FIND_ROW}; rest of the page {b.FIND_FIXED}; "
            f"90th percentile page {n(b.FIND_P90)}",
            f"row max {m['find_row_max']}, rest max {m['find_fixed_max']}, "
            f"90th percentile {n(m['find_p90'])} (max {n(m['find_max'])})",
        ),
        (
            "`nx_find_tools` domain overview (empty query, one row per domain)",
            f"row {b.OVERVIEW_ROW}; rest {b.OVERVIEW_FIXED}; no total",
            f"row max {m['overview_row_max']}, rest {m['overview_fixed']} "
            f"({n(m['overview'])} in all)",
        ),
        (
            "`nx_get_tool_schemas` entry, over the tool's definition",
            f"each {b.SCHEMA_OVERHEAD}; mean {b.SCHEMA_OVERHEAD_MEAN}",
            f"max {m['schema_overhead_max']}, mean {n(round(m['schema_overhead_mean'], 1))}",
        ),
        (
            "Typical modeling task (overview, 3 searches, 4 schemas in one fetch)",
            n(b.TYPICAL_TASK),
            f"{n(m['typical_task'])} ({tokens(m['typical_task'], t)})",
        ),
    ]
    lines = [
        BEGIN,
        "",
        "| Item (characters of compact JSON) | Cap | Measured |",
        "|---|---|---|",
        *(f"| {item} | {cap} | {measured} |" for item, cap, measured in rows),
        "",
        END,
    ]
    return "\n".join(lines)


def replace(text: str, table: str) -> str:
    start, end = text.find(BEGIN), text.find(END)
    if start < 0 or end < start:
        raise SystemExit(f"{DOC}: the budget table markers are missing")
    return text[:start] + table + text[end + len(END) :]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DOC)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    current = args.output.read_text(encoding="utf-8")
    result = replace(current, render(*load()))
    if args.check:
        if current != result:
            print(f"Budget table is stale: {args.output}; regenerate with this script.")
            return 1
        print("Budget table matches the measured values.")
        return 0
    args.output.write_text(result, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
